from pathlib import Path
from typing import Iterable, Protocol


class SubmissionUnknown(Exception):
    """Request might have been accepted; MUST NOT automatically resubmit."""


class RateLimited(Exception):
    """Explicit pre-acceptance rejection, safe to retry within the send allowance."""


class BatchProvider(Protocol):
    def validate(self, profile: str, snapshots: list[dict]) -> dict: ...
    def build_jsonl(self, path: Path, requests: Iterable[dict]) -> str: ...
    def upload(self, path: Path) -> str: ...
    def submit(self, input_name: str, model: str, display_key: str) -> str: ...
    def find(self, display_key: str) -> list[str]: ...
    def poll(self, remote_name: str) -> dict: ...
    def fetch(self, result_reference: str, local_temp_path: Path) -> None: ...
    def parse_line(self, line: str) -> dict: ...
